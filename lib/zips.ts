export const zipTown = new Map(entries);

export function lookupZip(raw: string) {
  const zip = raw.replace(/\D/g, "").slice(0, 5);
  if (zip.length !== 5) return { status: "invalid" as const, zip, town: null };
  const town = zipTown.get(zip) ?? null;
  if (!town) return { status: "out" as const, zip, town: null };
  return { status: "in" as const, zip, town };
}
